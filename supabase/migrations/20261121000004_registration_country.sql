-- ---------------------------------------------------------------------------
-- 2. The entry's country: a code of tbl_fencing_country, or nothing for an
--    entry made before the release (an administrator sets it, release 4).
--    One statement, last in the transaction, so the table's lock is held for
--    nothing else. NOT VALID: new rows are checked at once; every existing row
--    is NULL (the column is new), so there is nothing to validate.
-- ---------------------------------------------------------------------------
ALTER TABLE tbl_registration
  ADD COLUMN IF NOT EXISTS txt_country TEXT,
  ADD CONSTRAINT fk_registration_country FOREIGN KEY (txt_country)
    REFERENCES tbl_fencing_country (txt_code) NOT VALID;
