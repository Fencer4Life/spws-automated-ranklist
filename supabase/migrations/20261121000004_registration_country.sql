-- 1. tbl_fencing_country — the three-letter fencing codes an entry may declare
--    (the IOC codes the FIE uses: the letters on a fencer's jacket), each with
--    the two-letter code of its drawn flag. The same table is written out in
--    frontend/src/lib/fencingCountries.ts; RFCTRY.01 compares the two.
-- 2. tbl_registration.txt_country, a code of that table or nothing.
-- The write paths, the public view and the export follow in 20261121000005.
-- Tests: supabase/tests/132_registration_country.sql (RFCTRY.18–23).
-- =============================================================================

-- Supabase runs this file in one transaction; the ALTER of tbl_registration
-- is its last statement, so that table's lock is held for nothing else.
SET lock_timeout = '2s';

CREATE TABLE IF NOT EXISTS tbl_fencing_country (
  txt_code TEXT PRIMARY KEY CHECK (txt_code ~ '^[A-Z]{3}$'),
  txt_iso2 TEXT CHECK (txt_iso2 ~ '^[A-Z]{2}$')
);

COMMENT ON TABLE tbl_fencing_country IS
  'FR-169: the fencing codes a registration may declare, with the ISO-3166 alpha-2 code of each drawn flag (NULL: no drawn flag, AIN and TPE).';

ALTER TABLE tbl_fencing_country ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON tbl_fencing_country FROM PUBLIC, anon, authenticated;
GRANT SELECT ON tbl_fencing_country TO service_role;

